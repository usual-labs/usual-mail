// Copies what the chat views need from design/dist/web into src/ui/design.generated.ts, so the connector
// carries the design system as plain strings and needs no file access at run time (it must run on Cloudflare).
// `node scripts/build-design.mjs` writes the file; `--check` fails when it is out of date.
import { readFileSync, writeFileSync } from "node:fs";

const web = new URL("../../design/dist/web/", import.meta.url);
const target = new URL("../src/ui/design.generated.ts", import.meta.url);

/** The icons the views draw. Each must exist in the sprite. */
const ICONS = ["done", "reply-later", "set-aside", "come-back", "attachment", "undo"];

const tokensCss = readFileSync(new URL("tokens.css", web), "utf8");
const sprite = readFileSync(new URL("icons.svg", web), "utf8");

// The light block comes first in tokens.css; a hat's key is its light fill.
const lightBlock = tokensCss.slice(0, tokensCss.indexOf("@media (prefers-color-scheme: dark)"));
const hats = [...lightBlock.matchAll(/--color-hat-([a-z]+)-fill:\s*(#[0-9a-f]{6});/g)].map((m) => [m[1], m[2]]);
if (hats.length !== 12) throw new Error(`expected 12 hat fills in tokens.css, found ${hats.length}`);

const symbols = ICONS.map((name) => {
  const match = sprite.match(new RegExp(`<symbol id="icon-${name}"[\\s\\S]*?</symbol>`));
  if (!match) throw new Error(`icon-${name} is not in design/dist/web/icons.svg`);
  return match[0];
});

const out = `// Generated by scripts/build-design.mjs from design/dist/web. Do not edit; run \`npm run build:design\`.
// Icons: Hugeicons free set (Stroke Rounded), MIT, as shipped in design/dist/web/icons-LICENSE.md.

/** design/dist/web/tokens.css, unchanged. */
export const TOKENS_CSS = ${JSON.stringify(tokensCss)};

/** The twelve hats and their light fill, which is a hat's key. */
export const HAT_FILLS: ReadonlyArray<readonly [name: string, fill: string]> = ${JSON.stringify(hats)};

/** The sprite's symbols for the icons the views use. */
export const ICON_SYMBOLS = ${JSON.stringify(symbols.join("\n"))};
`;

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(target, "utf8");
  } catch {}
  if (current !== out) {
    console.error("src/ui/design.generated.ts is out of date with design/dist/web. Run `npm run build:design`.");
    process.exit(1);
  }
  console.log("src/ui/design.generated.ts is current.");
} else {
  writeFileSync(target, out);
  console.log("Wrote src/ui/design.generated.ts.");
}
