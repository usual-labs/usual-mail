// Writes src/generated/assets.ts: the design system's web output (design/dist/web: tokens.css, fonts.css, the fonts,
// the icon sprite and the licences) and the dashboard's own assets/dashboard.css, so the handler serves them with no
// file reads at run time. Each asset gets a content-hashed path under /assets/, so browsers may keep it for good.
//
//   node scripts/embed.mjs           write the module when it changed
//   node scripts/embed.mjs --check   fail when the module on disk is not what this would write
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = join(dirname(fileURLToPath(import.meta.url)), "..");
const web = join(here, "..", "design", "dist", "web");
const out = join(here, "src", "generated", "assets.ts");

const TYPES = {
  ".css": "text/css; charset=utf-8",
  ".svg": "image/svg+xml",
  ".woff2": "font/woff2",
  ".ttf": "font/ttf",
  ".txt": "text/plain; charset=utf-8",
  ".md": "text/plain; charset=utf-8",
};

const hash = (bytes) => createHash("sha256").update(bytes).digest("hex").slice(0, 10);
const extOf = (name) => name.slice(name.lastIndexOf("."));

/** Builds the module's text from the files on disk. */
export function generate() {
  const read = (path) => readFileSync(path);
  const paths = {};
  const assets = {};
  const add = (name, bytes) => {
    const ext = extOf(name);
    const path = `/assets/${name.slice(0, -ext.length)}.${hash(bytes)}${ext}`;
    const text = TYPES[ext].startsWith("text/") || ext === ".svg";
    paths[name] = path;
    assets[path] = { type: TYPES[ext], base64: !text, body: text ? bytes.toString("utf8") : bytes.toString("base64") };
  };

  // Fonts first, because the stylesheet refers to them by their hashed names, relative to /assets/.
  const fonts = ["Geist-Variable.woff2", "GeistSerif-Regular.woff2", "Prociono-Regular.ttf"];
  for (const font of fonts) add(`fonts/${font}`, read(join(web, "fonts", font)));
  for (const licence of ["Geist-OFL.txt", "Prociono-OFL.txt"]) add(`licences/${licence}`, read(join(web, "fonts", licence)));
  add("licences/icons-LICENSE.md", read(join(web, "icons-LICENSE.md")));
  add("icons.svg", read(join(web, "icons.svg")));

  const fontsCss = read(join(web, "fonts.css")).toString("utf8").replace(/url\("(fonts\/[^"]+)"\)/g, (match, ref) => {
    if (!paths[ref]) throw new Error(`fonts.css refers to ${ref}, which is not embedded`);
    return `url("${paths[ref].slice("/assets/".length)}")`;
  });
  const tokensCss = read(join(web, "tokens.css")).toString("utf8");
  const ownCss = read(join(here, "assets", "dashboard.css")).toString("utf8");
  add("app.css", Buffer.from(`${fontsCss}\n${tokensCss}\n${ownCss}`, "utf8"));

  // The twelve hats, keyed by their light fill: the first block of tokens.css is the light one.
  const light = tokensCss.slice(0, tokensCss.indexOf("@media"));
  const hats = [...light.matchAll(/--color-hat-([a-z]+)-fill: (#[0-9a-f]{6});/g)].map(([, name, key]) => ({ name, key }));
  if (hats.length !== 12) throw new Error(`Expected 12 hats in tokens.css, found ${hats.length}`);

  const icons = [...read(join(web, "icons.svg")).toString("utf8").matchAll(/<symbol id="icon-([a-z-]+)"/g)].map((m) => m[1]);

  return (
    "// Generated by scripts/embed.mjs from design/dist/web and assets/dashboard.css. Don't edit; run `npm run embed`.\n" +
    `export const ASSET_PATHS: Record<string, string> = ${JSON.stringify(paths, null, 2)};\n\n` +
    `export const HAT_KEYS: ReadonlyArray<{ name: string; key: string }> = ${JSON.stringify(hats, null, 2)};\n\n` +
    `export const ICON_NAMES: readonly string[] = ${JSON.stringify(icons)};\n\n` +
    "export const ASSETS: Record<string, { type: string; base64: boolean; body: string }> = " +
    `${JSON.stringify(assets, null, 2)};\n`
  );
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];
if (isMain) {
  const text = generate();
  const current = existsSync(out) ? readFileSync(out, "utf8") : null;
  if (process.argv.includes("--check")) {
    if (current !== text) {
      console.error("src/generated/assets.ts is stale: design/dist/web or assets/dashboard.css changed. Run `npm run embed`.");
      process.exit(1);
    }
    console.log("Embedded assets are current.");
  } else if (current !== text) {
    mkdirSync(dirname(out), { recursive: true });
    writeFileSync(out, text);
    console.log("Wrote src/generated/assets.ts.");
  } else {
    console.log("src/generated/assets.ts is already current.");
  }
}
