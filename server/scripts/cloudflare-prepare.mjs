// Prepares a checkout for the Cloudflare side (docs/agents/server-cloudflare.md): installs the part folders the Worker
// bundles, then writes src/cloudflare/migrations.generated.ts from migrations/, so both hosts run the same frozen files.
//
// Run by the repository root's `npm ci` (postinstall) and `npm run build`, by wrangler.jsonc's build step before every
// `wrangler deploy`, and by `npm run check:cloudflare`. A fresh clone has no node_modules anywhere: each part the server
// names as "file:../<folder>" (core, mail, dashboard, mcp) and the server itself are installed from their own lockfiles
// with production dependencies only, as the Dockerfile installs the parts. A folder that already has node_modules is
// left as it is, so a developer's installs (with their dev dependencies) are never replaced.
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const serverDir = new URL("../", import.meta.url);
const rootDir = new URL("../", serverDir);
const pkg = JSON.parse(readFileSync(new URL("package.json", serverDir), "utf8"));
const parts = Object.values(pkg.dependencies ?? {}).filter((spec) => spec.startsWith("file:../")).map((spec) => spec.slice("file:../".length));

for (const folder of [...parts, "server"]) {
  const dir = new URL(`${folder}/`, rootDir);
  if (existsSync(new URL("node_modules", dir)) || !existsSync(new URL("package-lock.json", dir))) continue;
  console.log(`Installing ${folder}/ (production dependencies, from its lockfile)`);
  execFileSync("npm", ["ci", "--omit=dev", "--no-audit", "--no-fund"], {
    cwd: fileURLToPath(dir),
    stdio: "inherit",
    shell: process.platform === "win32",
  });
}

// The migrations module, in the shape drizzle's durable-sqlite migrator takes: the journal and each file's SQL by
// `m<idx>`. Written only when it changes, so wrangler's watcher doesn't rebuild for nothing.
const migrationsDir = new URL("migrations/", serverDir);
const journal = JSON.parse(readFileSync(new URL("meta/_journal.json", migrationsDir), "utf8"));
const migrations = {};
for (const entry of journal.entries) {
  migrations[`m${String(entry.idx).padStart(4, "0")}`] = readFileSync(new URL(`${entry.tag}.sql`, migrationsDir), "utf8");
}
const out = new URL("src/cloudflare/migrations.generated.ts", serverDir);
const text = [
  "// Generated by server/scripts/cloudflare-prepare.mjs from server/migrations/, the files the Node server applies.",
  "// Written again at every install, build and wrangler deploy; not edited by hand and not kept in git.",
  "",
  `export const migrationConfig = ${JSON.stringify({ journal, migrations }, null, 2)};`,
  "",
].join("\n");
if (!existsSync(out) || readFileSync(out, "utf8") !== text) writeFileSync(out, text);
console.log(`Cloudflare: ${journal.entries.length} migrations written to server/src/cloudflare/migrations.generated.ts`);
