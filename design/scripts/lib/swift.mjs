// Writes the generated Swift sources of the UsualMailDesign package. The types they fill in (UsualRGB, UsualHat,
// UsualTextStyle, UsualDuration, ...) are hand-written beside Generated/.
import { swiftCase } from "./icons.mjs";

const HEADER = "// Generated by design/scripts/build.mjs from design/tokens.json. Do not edit; run `npm run build` in design/.\n";

const camel = (name) => swiftCase(name);
const hex = (h) => "0x" + h.slice(1).toUpperCase();
const num = (n) => Number(n.toFixed(4)).toString();
const doc = (text, indent = "    ") => (text ? `${indent}/// ${text}\n` : "");
const str = (s) => `"${String(s).replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\n/g, "\\n")}"`;
const rgb = (c) => (c.alpha === 1 ? `.init(${hex(c.hex)})` : `.init(${hex(c.hex)}, alpha: ${num(c.alpha)})`);
const pair = (p) => `UsualColorPair(light: ${rgb(p.light)}, dark: ${rgb(p.dark)})`;

/** A Swift identifier for a token name: "line-strong" becomes lineStrong, "16" becomes s16 for space. */
const ident = (name, prefix = "") => (/^\d/.test(name) ? prefix + name : camel(name));

export function colorsSwift(model) {
  const lines = model.colors.map(
    (c) => doc(c.description) + `    public static let ${ident(c.name)} = Color(${pair({ light: c.light, dark: c.dark })})\n`,
  );
  const swatches = model.colors.map((c) => `        UsualColorSwatch(name: ${str(c.name)}, colors: ${pair({ light: c.light, dark: c.dark })}),`);
  return (
    HEADER +
    "import SwiftUI\n\n" +
    "/// Usual Mail's colours. Each follows the system's light and dark appearance.\n" +
    "public enum UsualColor {\n" +
    lines.join("\n") +
    "\n    /// Every colour with its light and dark values, in token order, for galleries and tests.\n" +
    "    public static let swatches: [UsualColorSwatch] = [\n" +
    swatches.join("\n") +
    "\n    ]\n}\n"
  );
}

export function hatsSwift(model) {
  const hats = model.hats.map(
    (h) =>
      `    public static let ${ident(h.name)} = UsualHat(\n` +
      `        name: ${str(h.name)}, key: ${str(h.fill.light.hex)},\n` +
      `        fill: ${pair(h.fill)},\n` +
      `        on: ${pair(h.on)},\n` +
      `        tint: ${pair(h.tint)})\n`,
  );
  return (
    HEADER +
    "import SwiftUI\n\n" +
    "extension UsualHat {\n" +
    hats.join("\n") +
    "\n    /// Every hat in palette order.\n" +
    `    public static let all: [UsualHat] = [${model.hats.map((h) => ident(h.name)).join(", ")}]\n}\n`
  );
}

export function typeSwift(model, plan) {
  const weights = Object.entries(model.weights).map(([name, value]) => `    case ${ident(name)} = ${value}`);
  const families = Object.entries(model.families).map(([name, f]) => doc(f.description) + `    case ${ident(name)}`);
  const roles = model.type.map((t) => doc(t.description) + `    case ${ident(t.name)}`);
  const styles = model.type.map(
    (t) =>
      `        case .${ident(t.name)}:\n` +
      `            UsualTextStyle(\n` +
      `                family: .${ident(t.family)}, size: ${num(t.size)}, iphoneSize: ${num(t.iphoneSize)}, weight: .${ident(weightName(model, t.weight))},\n` +
      `                lineHeight: ${num(t.lineHeight)}, tracking: ${num(t.tracking)}, textStyle: ${t.appleTextStyle ? "." + t.appleTextStyle : "nil"})`,
  );
  const faces = plan.apple.map(
    (f) => `        UsualFontFace(family: .${ident(f.family)}, weight: ${f.weight}, postScriptName: ${str(f.postScript)}, file: ${str(f.file)}),`,
  );
  return (
    HEADER +
    "import SwiftUI\n\n" +
    "/// The font weights tokens.json defines. Only Geist Sans has more than regular.\n" +
    "public enum UsualFontWeight: Int, CaseIterable, Sendable {\n" +
    weights.join("\n") +
    "\n}\n\n" +
    "/// The four families. Mono is the system's monospace and ships no file.\n" +
    "public enum UsualFontFamily: CaseIterable, Sendable {\n" +
    families.join("\n") +
    "\n}\n\n" +
    "/// Usual Mail's text roles. Set one with `.usualFont(_:)`.\n" +
    "public enum UsualTextRole: String, CaseIterable, Sendable {\n" +
    roles.join("\n") +
    "\n\n    /// The role's values at the default text size.\n" +
    "    public var style: UsualTextStyle {\n        switch self {\n" +
    styles.join("\n") +
    "\n        }\n    }\n}\n\n" +
    "extension UsualFonts {\n" +
    "    /// The font files bundled in Resources/Fonts, one per family and weight.\n" +
    "    public static let faces: [UsualFontFace] = [\n" +
    faces.join("\n") +
    "\n    ]\n}\n"
  );
}

function weightName(model, value) {
  const found = Object.entries(model.weights).find(([, v]) => v === value);
  if (!found) throw new Error(`No font.weight token has the value ${value}`);
  return found[0];
}

export function metricsSwift(model) {
  const group = (name, summary, items, prefix) =>
    `/// ${summary}\npublic enum ${name} {\n` +
    items.map((i) => doc(i.description) + `    public static let ${ident(i.name, prefix)}: CGFloat = ${num(i.px)}`).join("\n") +
    "\n}\n";
  return (
    HEADER +
    "import CoreGraphics\n\n" +
    group("UsualSpace", "Spacing in points, named by size: `UsualSpace.s16` is 16 pt.", model.space, "s") +
    "\n" +
    group("UsualRadius", "Corner radii in points.", model.radius) +
    "\n" +
    group("UsualSize", "Fixed sizes in points: icons, dots, the smallest hit target, the reading measure.", model.size)
  );
}

export function motionSwift(model) {
  const durations = model.durations.map(
    (d) => doc(d.description) + `    public static let ${ident(d.name)} = UsualDuration(seconds: ${num(d.ms / 1000)}, reducedSeconds: ${num(d.reducedMs / 1000)})`,
  );
  const easings = model.easings.map((e) => doc(e.description) + `    public static let ${ident(e.name)} = UsualEasing(${e.points.map(num).join(", ")})`);
  return HEADER + "\nextension UsualDuration {\n" + durations.join("\n") + "\n}\n\nextension UsualEasing {\n" + easings.join("\n") + "\n}\n";
}

export function iconsSwift(icons, version) {
  const cases = icons.map((i) => `    /// ${i.for} (Hugeicons ${i.hugeicons}).\n    case ${ident(i.name)} = ${str(i.name)}`);
  return (
    HEADER.replace("tokens.json", "icons.json") +
    `\n/// The icons Usual Mail uses: Hugeicons' free set, Stroke Rounded, @hugeicons/core-free-icons ${version} (MIT).\n` +
    "/// Each is a template image in Icons.xcassets, so it takes the foreground colour.\n" +
    "public enum UsualIcon: String, CaseIterable, Sendable {\n" +
    cases.join("\n") +
    "\n}\n"
  );
}

export function sampleSwift(content) {
  const opt = (v) => (v === null || v === undefined ? "nil" : str(v));
  const hats = content.hats.map(
    (h) =>
      `            GalleryInbox(name: ${str(h.name)}, address: ${str(h.address)}, stored: ${str(h.stored)}, hat: ${str(h.hat)}, ` +
      `icon: .${ident(h.icon)}, trust: ${str(h.trust)}, trustIcon: .${ident(h.trustIcon)}, attention: ${opt(h.attention)}),`,
  );
  const sections = content.brief.sections.map(
    (s) =>
      `                GalleryBriefSection(\n` +
      `                    hat: ${str(s.hat)}, inbox: ${str(s.inbox)}, summary: ${opt(s.summary)},\n` +
      `                    highlights: [${s.highlights.map((h) => `GalleryHighlight(line: ${str(h.line)}, subject: ${str(h.subject)})`).join(", ")}],\n` +
      `                    counts: ${str(s.counts)}),`,
  );
  const rows = content.rows.map(
    (r) =>
      `            GalleryRow(\n` +
      `                id: ${str(r.id)}, hat: ${str(r.hat)}, inbox: ${str(r.inbox)}, sender: ${str(r.sender)}, subject: ${str(r.subject)},\n` +
      `                snippet: ${str(r.snippet)}, time: ${str(r.time)}, messageCount: ${r.messageCount}, unread: ${r.unread},\n` +
      `                attachment: ${r.attachment}, done: ${r.done}, category: ${str(r.category)}, stack: ${opt(r.stack)}, ` +
      `stackIcon: ${r.stackIcon ? "." + ident(r.stackIcon) : "nil"},\n` +
      `                comeBack: ${opt(r.comeBack)}, selected: ${r.selected}),`,
  );
  const reasons = content.reasons.map(
    (r) =>
      `            GalleryReason(\n` +
      `                id: ${str(r.id)}, hat: ${str(r.hat)}, inbox: ${str(r.inbox)}, subject: ${str(r.subject)}, icon: .${ident(r.icon)},\n` +
      `                actor: ${str(r.actor)}, action: ${str(r.action)}, reason: ${opt(r.reason)}, time: ${str(r.time)},\n` +
      `                state: ${str(r.state)}, undoable: ${r.undoable}),`,
  );
  return (
    HEADER.replace("design/tokens.json", "core/fixtures/sample.json") +
    "\nextension GalleryContent {\n" +
    "    /// The made-up content of core/fixtures/sample.json, with labels written as the HTML gallery writes them.\n" +
    "    static let sample = GalleryContent(\n" +
    "        inboxes: [\n" +
    hats.join("\n") +
    "\n        ],\n" +
    "        brief: GalleryBrief(\n" +
    `            title: ${str(content.brief.title)}, period: ${str(content.brief.period)}, writtenBy: ${str(content.brief.writtenBy)},\n` +
    "            sections: [\n" +
    sections.join("\n") +
    "\n            ]),\n" +
    "        rows: [\n" +
    rows.join("\n") +
    "\n        ],\n" +
    "        reasons: [\n" +
    reasons.join("\n") +
    "\n        ],\n" +
    "        typeSamples: [\n" +
    Object.entries(content.typeSamples).map(([role, text]) => `            .${ident(role)}: ${str(text)},`).join("\n") +
    "\n        ])\n}\n"
  );
}
