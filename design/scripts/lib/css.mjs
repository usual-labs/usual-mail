// Writes dist/web/tokens.css and dist/web/fonts.css.
import { cssColor } from "./color.mjs";

const HEADER = "/* Generated by design/scripts/build.mjs from design/tokens.json. Do not edit; run `npm run build` in design/. */\n";

const round = (n) => Number(n.toFixed(4)).toString();
const rem = (px) => `${round(px / 16)}rem`;
const length = (px) => (px === 0 ? "0" : `${round(px)}px`);
const quoteFamily = (name) => (/^[a-z-]+$/.test(name) ? name : `"${name}"`); // generic families stay bare
const stack = (family) => family.stack.map(quoteFamily).join(", ");
const shadowCss = (layers) =>
  layers.map((l) => `${l.inset ? "inset " : ""}${[l.x, l.y, l.blur, l.spread].map(length).join(" ")} ${cssColor(l.color)}`).join(", ");

/** The colour and elevation declarations for one appearance. */
function themed(model, mode) {
  const lines = [`  color-scheme: ${mode};`];
  for (const c of model.colors) lines.push(`  --color-${c.name}: ${cssColor(c[mode])};`);
  for (const hat of model.hats) {
    for (const part of ["fill", "on", "tint"]) lines.push(`  --color-hat-${hat.name}-${part}: ${cssColor(hat[part][mode])};`);
  }
  for (const e of model.elevation) lines.push(`  --elevation-${e.name}: ${shadowCss(e[mode])};`);
  return lines.join("\n");
}

export function tokensCss(model) {
  const fixed = [];
  for (const [name, family] of Object.entries(model.families)) fixed.push(`  --font-family-${name}: ${stack(family)};`);
  for (const [name, weight] of Object.entries(model.weights)) fixed.push(`  --font-weight-${name}: ${weight};`);
  for (const t of model.type) {
    const p = `--type-${t.name}`;
    fixed.push(
      `  ${p}-family: var(--font-family-${t.family});`,
      `  ${p}-size: ${rem(t.size)};`,
      `  ${p}-weight: ${t.weight};`,
      `  ${p}-line-height: ${round(t.lineHeight)};`,
      `  ${p}-tracking: ${t.tracking === 0 ? "0" : `${round(t.tracking)}em`};`,
      `  ${p}: ${t.weight} ${rem(t.size)}/${round(t.lineHeight)} var(--font-family-${t.family});`,
    );
  }
  for (const s of model.space) fixed.push(`  --space-${s.name}: ${s.px}px;`);
  for (const r of model.radius) fixed.push(`  --radius-${r.name}: ${r.px}px;`);
  for (const s of model.size) fixed.push(`  --size-${s.name}: ${s.px}px;`);
  for (const d of model.durations) fixed.push(`  --motion-duration-${d.name}: ${d.ms}ms;`);
  for (const e of model.easings) fixed.push(`  --motion-easing-${e.name}: cubic-bezier(${e.points.join(", ")});`);

  const reduced = model.durations.filter((d) => d.reducedMs !== d.ms).map((d) => `    --motion-duration-${d.name}: ${d.reducedMs}ms;`);
  const hats = model.hats.map(
    (hat) =>
      `[data-hat="${hat.name}"] {\n` +
      ["fill", "on", "tint"].map((part) => `  --hat-${part}: var(--color-hat-${hat.name}-${part});`).join("\n") +
      "\n}",
  );

  return [
    HEADER,
    "/* Light is the default. Dark follows the reader's setting unless data-theme on an element says otherwise;",
    '   data-theme="light" or "dark" on any element sets that appearance for everything inside it. */',
    ':root,\n[data-theme="light"] {\n' + themed(model, "light") + "\n}\n",
    '@media (prefers-color-scheme: dark) {\n  :root:not([data-theme="light"]) {\n' +
      themed(model, "dark").replace(/^/gm, "  ") +
      "\n  }\n}\n",
    '[data-theme="dark"] {\n' + themed(model, "dark") + "\n}\n",
    "/* Values that are the same in light and dark. Type sizes are rem, so they follow the reader's text size. */",
    ":root {\n" + fixed.join("\n") + "\n}\n",
    "/* Movement stops for readers who ask for reduced motion; fades keep their duration. */",
    "@media (prefers-reduced-motion: reduce) {\n  :root {\n" + reduced.join("\n") + "\n  }\n}\n",
    "/* A company's hat: data-hat=\"<name>\" sets --hat-fill, --hat-on and --hat-tint for everything inside. */",
    hats.join("\n\n") + "\n",
  ].join("\n");
}

export function fontsCss(plan) {
  const faces = plan.web.map(
    (f) =>
      `@font-face {\n  font-family: "${f.family}";\n  src: url("fonts/${f.file}") format("${f.format}");\n` +
      `  font-weight: ${f.weight};\n  font-style: normal;\n  font-display: ${f.display};\n}`,
  );
  return (
    HEADER +
    "\n/* Geist Serif has one weight and no italic, and only Geist Sans has real weights. Set font-synthesis: none where the\n" +
    "   serif or the wordmark is used, so a browser never draws a fake bold or italic. Licences: fonts/*-OFL.txt. */\n\n" +
    faces.join("\n\n") +
    "\n"
  );
}
