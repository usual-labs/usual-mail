// Takes exactly the icons icons.json names from Hugeicons' free package and writes them for the web (one SVG sprite)
// and for Swift (an asset catalog of template SVGs).
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { pathToFileURL } from "node:url";
import { PACKAGES } from "./paths.mjs";

const PACKAGE = join(PACKAGES, "@hugeicons", "core-free-icons");

export function readIconList(file) {
  const list = JSON.parse(readFileSync(file, "utf8"));
  const problems = [];
  for (const [name, entry] of Object.entries(list.icons ?? {})) {
    if (!/^[a-z][a-z0-9]*(-[a-z0-9]+)*$/.test(name)) problems.push(`${name}: names are kebab-case`);
    if (typeof entry?.hugeicons !== "string") problems.push(`${name}: needs "hugeicons", the free package's export name`);
    if (typeof entry?.for !== "string" || !entry.for) problems.push(`${name}: needs "for", what the icon is used for`);
  }
  if (problems.length) throw new Error(`icons.json has problems:\n- ${problems.join("\n- ")}`);
  return Object.entries(list.icons)
    .map(([name, entry]) => ({ name, hugeicons: entry.hugeicons, for: entry.for }))
    .sort((a, b) => (a.name < b.name ? -1 : 1));
}

export function packageVersion() {
  return JSON.parse(readFileSync(join(PACKAGE, "package.json"), "utf8")).version;
}

export const packageLicence = () => join(PACKAGE, "LICENSE.md");

/** Loads each listed icon's shapes from the free package's own exports. Fails on a name the package doesn't have. */
export async function loadIcons(list) {
  const pkg = await import(pathToFileURL(join(PACKAGE, "dist", "esm", "index.js")).href);
  const missing = list.filter((icon) => !Array.isArray(pkg[icon.hugeicons]));
  if (missing.length) {
    throw new Error(`Not in @hugeicons/core-free-icons: ${missing.map((icon) => `${icon.name} (${icon.hugeicons})`).join(", ")}`);
  }
  return list.map((icon) => ({ ...icon, shapes: pkg[icon.hugeicons] }));
}

export const swiftCase = (name) => name.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());

const kebab = (key) => key.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);
const escape = (value) => String(value).replace(/&/g, "&amp;").replace(/"/g, "&quot;").replace(/</g, "&lt;");

/** The icon's shapes as SVG elements. `paint` replaces currentColor (templates in an asset catalog want a solid colour). */
export function shapesSvg(shapes, paint = "currentColor") {
  return shapes
    .map(([tag, attrs]) => {
      const parts = Object.entries(attrs)
        .filter(([key]) => key !== "key")
        .map(([key, value]) => `${kebab(key)}="${escape(value === "currentColor" ? paint : value)}"`);
      return `<${tag} ${parts.join(" ")}/>`;
    })
    .join("");
}

/** One sprite of <symbol id="icon-NAME">, used as <svg><use href="icons.svg#icon-NAME"/></svg>. Inherits currentColor. */
export function spriteSvg(icons, version) {
  const symbols = icons.map((icon) => `  <symbol id="icon-${icon.name}" viewBox="0 0 24 24" fill="none">${shapesSvg(icon.shapes)}</symbol>`);
  return (
    `<svg xmlns="http://www.w3.org/2000/svg">\n` +
    `  <!-- Generated by design/scripts/build.mjs from design/icons.json. Hugeicons free set (Stroke Rounded),\n` +
    `       @hugeicons/core-free-icons ${version}, MIT: see icons-LICENSE.md. -->\n` +
    symbols.join("\n") +
    "\n</svg>\n"
  );
}

/** A standalone template SVG for the asset catalog. Black, since a template image uses only its shape. */
export function templateSvg(icon) {
  return `<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none">${shapesSvg(icon.shapes, "#000000")}</svg>\n`;
}

const json = (value) => JSON.stringify(value, null, 2) + "\n";

/** The asset catalog's files, keyed by path inside Icons.xcassets. */
export function assetCatalog(icons) {
  const files = { "Contents.json": json({ info: { author: "xcode", version: 1 } }) };
  for (const icon of icons) {
    files[`${icon.name}.imageset/Contents.json`] = json({
      images: [{ filename: `${icon.name}.svg`, idiom: "universal" }],
      info: { author: "xcode", version: 1 },
      properties: { "preserves-vector-representation": true, "template-rendering-intent": "template" },
    });
    files[`${icon.name}.imageset/${icon.name}.svg`] = templateSvg(icon);
  }
  return files;
}
